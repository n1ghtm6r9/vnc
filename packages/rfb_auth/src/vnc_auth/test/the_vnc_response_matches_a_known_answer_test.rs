use crate::vnc_auth_response;

#[test]
fn test_the_vnc_response_matches_a_known_answer() {
    let challenge = [
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee,
        0xff,
    ];
    assert_eq!(
        vnc_auth_response(&challenge, "secret"),
        [
            0xf1, 0x9b, 0x50, 0x47, 0x1f, 0x60, 0xf4, 0x22, 0x98, 0xe5, 0xc0, 0x14, 0x7d, 0xb5,
            0x0e, 0x1e
        ],
        "the response equals what openssl des-ecb gives for the key cea6c64ea62e0000"
    );
}
