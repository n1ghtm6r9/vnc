use crate::md5_digest;

#[test]
fn test_md5_matches_the_rfc_1321_vectors() {
    assert_eq!(
        md5_digest(b""),
        [
            0xd4, 0x1d, 0x8c, 0xd9, 0x8f, 0x00, 0xb2, 0x04, 0xe9, 0x80, 0x09, 0x98, 0xec, 0xf8,
            0x42, 0x7e
        ],
        "the digest of the empty input"
    );
    assert_eq!(
        md5_digest(b"abc"),
        [
            0x90, 0x01, 0x50, 0x98, 0x3c, 0xd2, 0x4f, 0xb0, 0xd6, 0x96, 0x3f, 0x7d, 0x28, 0xe1,
            0x7f, 0x72
        ],
        "the digest of abc"
    );
    assert_eq!(
        md5_digest(b"message digest"),
        [
            0xf9, 0x6b, 0x69, 0x7d, 0x7c, 0xb7, 0x93, 0x8d, 0x52, 0x5a, 0x2f, 0x31, 0xaa, 0xf1,
            0x61, 0xd0
        ],
        "the digest of message digest"
    );
}
