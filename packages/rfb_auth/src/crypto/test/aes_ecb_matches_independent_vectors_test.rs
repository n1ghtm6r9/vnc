use crate::aes128_ecb_encrypt;

#[test]
fn test_aes_ecb_matches_independent_vectors() {
    let key: [u8; 16] = std::array::from_fn(|index| index as u8);
    let fips_plain: [u8; 16] = [
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee,
        0xff,
    ];
    let fips_cipher: [u8; 16] = [
        0x69, 0xc4, 0xe0, 0xd8, 0x6a, 0x7b, 0x04, 0x30, 0xd8, 0xcd, 0xb7, 0x80, 0x70, 0xb4, 0xc5,
        0x5a,
    ];

    let repeated: [u8; 128] = std::array::from_fn(|index| fips_plain[index % 16]);
    let encrypted = aes128_ecb_encrypt(&key, &repeated);
    for (index, chunk) in encrypted.as_chunks::<16>().0.iter().enumerate() {
        assert_eq!(
            *chunk, fips_cipher,
            "chunk {index} is the FIPS-197 ciphertext, so every 16-byte chunk is encrypted on its own"
        );
    }

    let varied: [u8; 128] =
        std::array::from_fn(|index| (index as u8).wrapping_mul(3).wrapping_add(1));
    let expected: [u8; 128] = [
        0xe8, 0xe9, 0x6a, 0xb0, 0xd5, 0xd7, 0xc2, 0x40, 0x25, 0xdb, 0x87, 0xed, 0xcb, 0x03, 0xd5,
        0xef, 0xa0, 0x9a, 0xf9, 0xf3, 0xcf, 0xef, 0xf8, 0x9e, 0x91, 0xc3, 0x33, 0x86, 0xea, 0x62,
        0xc9, 0xc5, 0xc7, 0xdd, 0xb2, 0xc8, 0x8b, 0x26, 0xa9, 0x50, 0x3a, 0xb2, 0x6f, 0xfe, 0xe6,
        0xa5, 0xb8, 0xe9, 0x1f, 0x86, 0x90, 0xb5, 0x11, 0xd8, 0x80, 0x6c, 0xcf, 0x3f, 0xcb, 0xc9,
        0xdd, 0xd5, 0x50, 0x41, 0x5f, 0x21, 0xc3, 0x83, 0xfa, 0x1b, 0x2d, 0x12, 0xa9, 0x76, 0xf9,
        0xf3, 0x13, 0x4d, 0xdf, 0xa9, 0xd8, 0xf4, 0x5c, 0xad, 0xd0, 0x3b, 0xe4, 0xb4, 0xc5, 0x7d,
        0xfd, 0x4c, 0x19, 0x06, 0x1b, 0x96, 0x47, 0xfa, 0x99, 0xd7, 0x91, 0xaa, 0xcf, 0xaf, 0x93,
        0xba, 0xc7, 0xed, 0x38, 0xbd, 0xde, 0x32, 0x29, 0xc1, 0xe7, 0xf2, 0x37, 0x3d, 0x9e, 0x5a,
        0x60, 0x6e, 0xdb, 0x85, 0x78, 0xfa, 0xd4, 0x63,
    ];
    assert_eq!(
        aes128_ecb_encrypt(&key, &varied),
        expected,
        "128 distinct bytes match what openssl aes-128-ecb produces, chunk by chunk in order"
    );
}
